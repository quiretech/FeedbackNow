void ssd1683_draw_char_fb(int x, int y, char c, uint8_t color) {
  if (c < 0 || c > 127)
    return;

  for (int row = 0; row < 8; row++) {
    uint8_t bits = font8x8_basic[(int)c][row];
    for (int col = 0; col < 8; col++) {
      if (bits & (1 << col)) { // LSB = leftmost
        ssd1683_set_pixel_fb(x + col, y + row, color);
      }
    }
  }
}
void ssd1683_draw_string_fb(int x, int y, const char *str, uint8_t color) {
  int cursor_x = x;
  while (*str) {
    ssd1683_draw_char_fb(cursor_x, y, *str, color);
    cursor_x += 8; // move 8px per char
    str++;
  }
}

void ssd1683_set_pixel_fb(int x, int y, uint8_t color) {
  if (x < 0 || x >= SSD1683_WIDTH || y < 0 || y >= SSD1683_HEIGHT)
    return;

  int byte_index = y * (SSD1683_WIDTH / 8) + (x / 8);
  uint8_t bit_mask = 0x80 >> (x % 8);

  switch (color) {
  case SSD1683_COLOR_BLACK:
    fb_bw[byte_index] &= ~bit_mask; // black = 0
    fb_red[byte_index] |= bit_mask; // make sure red is off
    break;

  case SSD1683_COLOR_RED:
    fb_red[byte_index] &= ~bit_mask; // red = 0
    fb_bw[byte_index] |= bit_mask;   // make sure bw is off
    break;

  default:                          // WHITE
    fb_bw[byte_index] |= bit_mask;  // white = 1
    fb_red[byte_index] |= bit_mask; // red = 1 (off)
    break;
  }
}

void ssd1683_draw_rect_fb(int x, int y, int w, int h, uint8_t color) {
  for (int j = y; j < y + h; j++) {
    for (int i = x; i < x + w; i++) {
      ssd1683_set_pixel_fb(i, j, color);
    }
  }
}

