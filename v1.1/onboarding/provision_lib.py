@dataclass(frozen=True)
class BuildProfile:
    hardware: str
    region: str

    def __post_init__(self) -> None:
        if self.hardware not in VALID_HARDWARE:
            raise ValueError(f"unknown hardware {self.hardware!r}")
        if self.region not in VALID_REGIONS:
            raise ValueError(f"unknown region {self.region!r}")
        if self.hardware == "lr62" and self.region != "us915":
            raise ValueError("LR62E radio is US915-only; use --preset seeed-eu868 for EU868")


def registry_dir(*, test: bool) -> Path:
    return DEMO_REGISTRY_DIR if test else REGISTRY_DIR


def registry_csv_path(region: str, *, test: bool) -> Path:
    name = REGISTRY_CSV_EU868 if region == "eu868" else REGISTRY_CSV_US915
    return registry_dir(test=test) / name


def master_registry_paths() -> list[Path]:
    paths = [REGISTRY_DIR / REGISTRY_CSV_US915, REGISTRY_DIR / REGISTRY_CSV_EU868]
    return [p for p in paths if p.exists()]


def demo_registry_paths() -> list[Path]:
    paths = [
        DEMO_REGISTRY_DIR / REGISTRY_CSV_US915,
        DEMO_REGISTRY_DIR / REGISTRY_CSV_EU868,
    ]
    return [p for p in paths if p.exists()]


def collision_registry_paths(*, test: bool) -> list[Path]:
    """All CSV files checked when generating new keys (master + demo_units)."""
    seen: set[Path] = set()
    out: list[Path] = []
    for p in master_registry_paths() + demo_registry_paths():
        rp = p.resolve()
        if rp not in seen:
            seen.add(rp)
            out.append(p)
    return out


def apply_build_profile(profile: BuildProfile) -> None:
    if profile.region == "us915":
        prj_inner = PRJ_INNER_US915
    else:
        prj_inner = PRJ_INNER_EU868

    ovl_inner = (
        OVERLAY_INNER_LR62 if profile.hardware == "lr62" else OVERLAY_INNER_SEED
    )

    if not PRJ_CONF.exists():
        raise RuntimeError(f"{PRJ_CONF} not found")
