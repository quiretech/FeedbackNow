def _parse_fw_hw_versions(sys_config_text: str) -> tuple[str, str]:
    fm = FW_VERSION_STRING_RE.search(sys_config_text)
    hm = HW_VERSION_STRING_RE.search(sys_config_text)
    if not fm or not hm:
        raise RuntimeError(f"Could not parse FW/HW version in {SYS_CONFIG_H}")
    return fm.group(1).strip(), hm.group(1).strip()


def _parse_device_hw_variant(onboarding_text: str) -> str:
    m = DEVICE_HW_VARIANT_RE.search(onboarding_text)
    if not m:
        raise RuntimeError(f"Could not parse DEVICE_HW_VARIANT in {ONBOARDING_CONFIG_H}")
    return m.group(1)


def validate_hw_variant_build() -> list[str]:
    """
    Check DEVICE_HW_VARIANT matches prj fragments, base overlay, and plus overlay.
    Returns human-readable ERROR:/WARNING: strings (empty if OK).
    """
    issues: list[str] = []
    onboarding_text = ONBOARDING_CONFIG_H.read_text(encoding="utf-8")
    variant = _parse_device_hw_variant(onboarding_text)
    prj_base = PRJ_CONF.read_text(encoding="utf-8")
    overlay_base = BOARD_OVERLAY.read_text(encoding="utf-8")

    enabled_in_base = {
        "PN5180": CONFIG_PN5180_Y_RE.search(prj_base),
        "SSD1683": CONFIG_SSD1683_Y_RE.search(prj_base),
        "DISPLAY": CONFIG_DISPLAY_Y_RE.search(prj_base),
        "LVGL": CONFIG_LVGL_Y_RE.search(prj_base),
    }
    for name, enabled in enabled_in_base.items():
        if enabled:
            issues.append(
                f"ERROR: {name} enabled in prj.conf; use prj_flexbox*.conf fragments only"
            )

    if SSD1683_DT_RE.search(overlay_base) or PN5180_DT_RE.search(overlay_base):
        issues.append(
            "ERROR: base overlay contains EPD/NFC nodes; use flexbox_plus overlay only"
        )

    if variant == "FLEXBOX":
        if not PRJ_FLEXBOX_CONF.exists():
            issues.append(f"ERROR: missing {PRJ_FLEXBOX_CONF.name}")
        if FLEXBOX_PLUS_OVERLAY.exists():
            plus_ovl = FLEXBOX_PLUS_OVERLAY.read_text(encoding="utf-8")
            if SSD1683_DT_RE.search(plus_ovl) or PN5180_DT_RE.search(plus_ovl):
                pass  # plus overlay is inert unless CMake selects it
    else:
        if not PRJ_FLEXBOX_PLUS_CONF.exists():
            issues.append(f"ERROR: missing {PRJ_FLEXBOX_PLUS_CONF.name}")
        else:
            plus_conf = PRJ_FLEXBOX_PLUS_CONF.read_text(encoding="utf-8")
            for name, regex in (
                ("PN5180", CONFIG_PN5180_Y_RE),
                ("SSD1683", CONFIG_SSD1683_Y_RE),
                ("DISPLAY", CONFIG_DISPLAY_Y_RE),
                ("LVGL", CONFIG_LVGL_Y_RE),
            ):
                if not regex.search(plus_conf):
                    issues.append(
                        f"ERROR: FLEXBOX_PLUS but {name} not enabled in "
                        f"{PRJ_FLEXBOX_PLUS_CONF.name}"
                    )
        if not FLEXBOX_PLUS_OVERLAY.exists():
            issues.append(f"ERROR: missing {FLEXBOX_PLUS_OVERLAY.name}")
        else:
            plus_ovl = FLEXBOX_PLUS_OVERLAY.read_text(encoding="utf-8")
            if not SSD1683_DT_RE.search(plus_ovl):
                issues.append(
                    f"ERROR: FLEXBOX_PLUS but no ssd1683 node in {FLEXBOX_PLUS_OVERLAY.name}"
                )
            if not PN5180_DT_RE.search(plus_ovl):
                issues.append(
                    f"ERROR: FLEXBOX_PLUS but no pn5180 node in {FLEXBOX_PLUS_OVERLAY.name}"
                )

    return issues


def _hardware_profile_code(onboarding_text: str, prj_text: str) -> str:
    del prj_text  # build fragments are validated separately
    variant = _parse_device_hw_variant(onboarding_text)
    if variant != "FLEXBOX_PLUS":
        return "FLEXBOX"
    if not PRJ_FLEXBOX_PLUS_CONF.exists():
        print(
            f"WARNING: missing {PRJ_FLEXBOX_PLUS_CONF.name} — registry hw_profile FLEXBOX",
            file=sys.stderr,
        )
        return "FLEXBOX"
    plus_conf = PRJ_FLEXBOX_PLUS_CONF.read_text(encoding="utf-8")
    if not CONFIG_PN5180_Y_RE.search(plus_conf):
        print(
            "WARNING: DEVICE_HW_VARIANT FLEXBOX_PLUS but CONFIG_PN5180 is not "
            f"enabled in {PRJ_FLEXBOX_PLUS_CONF.name} — registry hw_profile FLEXBOX",
            file=sys.stderr,
        )
        return "FLEXBOX"
    return "FLEXBOX_PLUS"


def _parse_registry_name_prefix(onboarding_text: str) -> str:
    m = REGISTRY_NAME_PREFIX_STRING_RE.search(onboarding_text)
    if not m:
        return ""
    s = m.group(1).strip()
    if s and not re.fullmatch(r"[A-Za-z0-9._-]+", s):
        raise RuntimeError(f"Invalid DEVICE_REGISTRY_NAME_PREFIX_STRING: {s!r}")
    return s


def _parse_registry_client_name(onboarding_text: str) -> str:
    m = REGISTRY_CLIENT_NAME_RE.search(onboarding_text)
    return m.group(1).strip() if m else ""


def _parse_registry_decal_type(onboarding_text: str) -> str:
    m = REGISTRY_DECAL_TYPE_RE.search(onboarding_text)
    return m.group(1).strip() if m else ""


def _registry_row_value(row: dict[str, str], new_key: str, legacy_key: str | None = None) -> str:
    v = (row.get(new_key) or "").strip()
    if v or not legacy_key:
        return v
    return (row.get(legacy_key) or "").strip()


def _fmt_c_array_hex(bytes_: bytes) -> str:
    return ", ".join(f"0x{b:02x}" for b in bytes_)


def _fmt_eui_define(name: str, eui: bytes) -> str:
    if len(eui) != 8:
        raise ValueError("EUI must be 8 bytes")
    return (
        f"#define {name}                                                        \\\n"
        f"  {{ {_fmt_c_array_hex(eui)} }}\n"
    )


def _fmt_app_key_define(app_key: bytes) -> str:
    if len(app_key) != 16:
        raise ValueError("AppKey must be 16 bytes")
    first = _fmt_c_array_hex(app_key[:12])
    last = _fmt_c_array_hex(app_key[12:])
    return (
        "#define LORAWAN_APP_KEY                                                        \\\n"
        "  {                                                                            \\\n"
        f"    {first},    \\\n"
        f"        {last}                                                 \\\n"
        "  }\n"
    )


def _eui64_local() -> bytes:
    b = bytearray(secrets.token_bytes(8))
    b[0] = (b[0] | 0x02) & 0xFE
    return bytes(b)


def _dev_eui() -> bytes:
    suffix = secrets.token_bytes(8 - len(DEV_EUI_PREFIX))
    b = bytearray(DEV_EUI_PREFIX + suffix)
    b[0] = (b[0] | 0x02) & 0xFE
    return bytes(b)


def _app_key() -> bytes:
    return secrets.token_bytes(16)


def _colon_hex(bytes_: bytes) -> str:
    return ":".join(f"{b:02X}" for b in bytes_)


def _plain_hex(bytes_: bytes) -> str:
    return "".join(f"{b:02X}" for b in bytes_)


def _normalize_hex_string(s: str) -> str:
    return re.sub(r"[^0-9A-Fa-f]", "", (s or "")).upper()


def _read_existing_registry(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _next_asset_id(existing_rows: Iterable[dict[str, str]], *, prefix: str = "UNIT-") -> str:
    max_n = 0
    for r in existing_rows:
        aid = (r.get("asset_id") or "").strip()
        if not aid.startswith(prefix):
            continue
        suffix = aid[len(prefix) :]
        if suffix.isdigit():
            max_n = max(max_n, int(suffix))
    return f"{prefix}{max_n + 1:04d}"


def _replace_between_markers(
    contents: str, begin_marker: str, end_marker: str, new_inner: str
) -> str:
    bi = contents.find(begin_marker)
    if bi < 0:
        raise RuntimeError(f"Missing begin marker {begin_marker!r}")
    line_end = contents.find("\n", bi)
    if line_end < 0:
        raise RuntimeError(f"Begin marker line has no newline: {begin_marker!r}")
    start_inner = line_end + 1
    ei = contents.find(end_marker, start_inner)
    if ei < 0:
        raise RuntimeError(f"Missing end marker {end_marker!r}")
    return contents[:start_inner] + new_inner + contents[ei:]


def _replace_onboarding_unit_id(contents: str, asset_id: str) -> str:
    if UNIT_ID_SYS_BEGIN not in contents or UNIT_ID_SYS_END not in contents:
        raise RuntimeError(f"Missing unit-id markers in {ONBOARDING_CONFIG_H}")
    if not re.fullmatch(r"[A-Za-z0-9._-]+", asset_id or ""):
        raise ValueError(f"asset_id unsafe for C string: {asset_id!r}")
    start = contents.index(UNIT_ID_SYS_BEGIN)
    end_idx = contents.index(UNIT_ID_SYS_END)
    end_line = contents.find("\n", end_idx)
    if end_line == -1:
        end_line = len(contents)
    block = (
        f"{UNIT_ID_SYS_BEGIN}\n"
        f'#define DEVICE_UNIT_ID_STRING "{asset_id}"\n'
        f"{UNIT_ID_SYS_END}\n"
    )
    return contents[:start] + block + contents[end_line + 1 :]


def _replace_onboarding_provision_utc(
    contents: str, unix_ts: int, iso8601_z: str
) -> str:
    if PROVISION_UTC_BEGIN not in contents or PROVISION_UTC_END not in contents:
        raise RuntimeError(f"Missing PROVISION_UTC markers in {ONBOARDING_CONFIG_H}")
    if not PROVISION_ISO_RE.fullmatch(iso8601_z):
        raise ValueError(f"iso8601_z must match ...Z format, got {iso8601_z!r}")
    start = contents.index(PROVISION_UTC_BEGIN)
    end_idx = contents.index(PROVISION_UTC_END)
    end_line = contents.find("\n", end_idx)
    if end_line == -1:
        end_line = len(contents)
    block = (
        f"{PROVISION_UTC_BEGIN}\n"
        f"#define DEVICE_PROVISION_UNIX_UTC {unix_ts}ULL\n"
        f'#define DEVICE_PROVISION_ISO8601_UTC "{iso8601_z}"\n'
        f"{PROVISION_UTC_END}\n"
    )
    return contents[:start] + block + contents[end_line + 1 :]


def _replace_generated_section(contents: str, generated_block: str) -> str:
    if BEGIN_MARKER not in contents or END_MARKER not in contents:
        raise RuntimeError(f"Missing generated markers in {EUI_KEYS_H}")
    start = contents.index(BEGIN_MARKER)
    end = contents.index(END_MARKER)
    end_line = contents.find("\n", end)
    if end_line == -1:
        end_line = len(contents)
    return contents[:start] + generated_block + contents[end_line + 1 :]


def _normalize_registry_csv(path: Path) -> None:
    if not path.exists() or path.stat().st_size == 0:
        return
    with path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames
        if not fieldnames:
            return
        if not {"asset_id", "dev_eui", "join_eui", "app_key"} <= set(fieldnames):
            return
        rows = list(reader)
    if tuple(fieldnames) == tuple(REGISTRY_FIELDS):
        return
    tmp = path.with_suffix(".csv.tmp")
    with tmp.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=REGISTRY_FIELDS, quoting=csv.QUOTE_ALL)
        writer.writeheader()
        for r in rows:
            out = {
                k: _registry_row_value(
                    r, k, legacy_key="tag_location" if k == "decal_type" else None
                )
                for k in REGISTRY_FIELDS
            }
            writer.writerow(out)
    tmp.replace(path)


def _atomic_write(path: Path, text: str) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
